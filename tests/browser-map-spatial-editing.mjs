import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const adminUrl=process.env.ADMIN_URL, user=process.env.TEST_ADMIN_EMAIL, password=process.env.TEST_ADMIN_PASSWORD;
if(!adminUrl||!user||!password)throw new Error('Missing disposable browser acceptance settings');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:950}});
const stage=page.locator('#grtrans-map-workspace');
const getForm=()=>stage.locator('#grtrans-network-editor form');
const chooseMode=label=>stage.getByRole('button',{name:label,exact:true}).first().click();
const useMapPoint=async (lat,lng)=>page.evaluate(([a,b])=>window.GrtransMapWorkspaceHooks.mapClick({lat:a,lng:b}),[lat,lng]);
try {
  await page.goto('http://localhost:8080/admin-dev/',{waitUntil:'domcontentloaded',timeout:45000});
  await page.locator('input[name="email"],input[type="email"]').first().fill(user);
  await page.locator('input[name="passwd"],input[type="password"]').first().fill(password);
  await page.locator('button[type="submit"]').first().click();
  await page.waitForLoadState('domcontentloaded');
  await page.goto(adminUrl,{waitUntil:'domcontentloaded',timeout:45000});
  await stage.waitFor({timeout:20000});
  const draw=stage.locator('[data-grtrans-mode="draw"]');
  const edit=stage.locator('[data-grtrans-mode="edit-coverage"]');
  assert.equal(await draw.isEnabled(),true,'Draw area placeholder becomes active');
  assert.equal(await edit.isEnabled(),true,'Edit coverage placeholder becomes active');
  assert.equal(await stage.getByRole('button',{name:'Set reach'}).isVisible(),true);
  assert.equal(await stage.getByRole('button',{name:'Edit route line'}).isVisible(),true);
  const stationRow=stage.locator('[data-grtrans-entity="stations"] tr[data-grtrans-record-id]').first();
  const id=Number(await stationRow.getAttribute('data-grtrans-record-id'));
  assert.ok(id>0,'Network fixture should have a station');
  const editLink=stationRow.locator('a[href*="network_edit="]').first();
  await editLink.click();await page.waitForURL(/network_entity=stations.*network_edit=/,{timeout:20000});
  await stage.waitFor();
  const stationForm=getForm();
  const beforeShape=await stationForm.locator('[name="coverage_geojson"]').inputValue();
  const beforeReach=await stationForm.locator('[name="inner_radius_km"]').inputValue();
  const centre=await page.evaluate(id=>{const s=window.GrtransMapBridge.station(id);return {lat:Number(s.lat),lng:Number(s.lng)};},id);
  await chooseMode('Draw area');
  const polygonType=stage.locator('select[data-grtrans-polygon-type]');
  if(await polygonType.count())await polygonType.selectOption('postal_polygon');
  if(!(await stage.getByRole('button',{name:'Finish ring'}).count())) await stage.getByRole('button',{name:'Add island'}).click();
  await useMapPoint(centre.lat+.03,centre.lng+.01);
  await useMapPoint(centre.lat+.03,centre.lng+.04);
  assert.equal(await stationForm.evaluate(form=>{
    const event=new Event('submit',{bubbles:true,cancelable:true});form.dispatchEvent(event);return event.defaultPrevented;
  }),true,'An incomplete ring must not reach the authenticated save handler');
  await useMapPoint(centre.lat+.06,centre.lng+.04);
  await stage.getByRole('button',{name:'Finish ring'}).click();
  const afterShape=await stationForm.locator('[name="coverage_geojson"]').inputValue();
  assert.notEqual(afterShape,beforeShape,'Polygon drawing should modify a draft, not auto-submit');
  const data=JSON.parse(afterShape);assert.ok(['Polygon','MultiPolygon'].includes(data.type));
  assert.ok(await stationForm.locator('.grtrans-spatial-unsaved').isVisible());
  await page.keyboard.press('Escape');
  assert.equal(await stationForm.locator('[name="coverage_geojson"]').inputValue(),beforeShape,'Escape restores original coverage field');
  await chooseMode('Set reach');
  const exact=stage.locator('input[aria-label="Reach in kilometres"]');
  const newRadius=(Number(beforeReach)+.25).toFixed(2);
  await exact.fill(newRadius);await stage.getByRole('button',{name:'Apply reach'}).click();
  assert.equal(Number(await stationForm.locator('[name="inner_radius_km"]').inputValue()),Number(newRadius));
  await page.keyboard.press('Escape');
  assert.equal(await stationForm.locator('[name="inner_radius_km"]').inputValue(),beforeReach);
  await chooseMode('Place service area');
  await page.waitForURL(/network_entity=legs/,{timeout:20000});
  await stage.waitFor();
  const areaForm=getForm();
  assert.equal(await areaForm.locator('[name="network_entity"]').inputValue(),'legs');
  const stations=await page.evaluate(()=>window.GrtransMapBridge.data.stations.map(s=>Number(s.id_station)));
  await page.evaluate(id=>{const bridge=window.GrtransMapBridge;bridge.marker(id).fire('click',{latlng:bridge.marker(id).getLatLng()});},stations[0]);
  assert.equal(await areaForm.locator('select[name="from_station_id"]').inputValue(),String(stations[0]));
  await useMapPoint(centre.lat+.2,centre.lng+.2);
  const areaLat=await areaForm.locator('[name="area_lat"]').inputValue();
  assert.ok(areaLat!==''&&Number(areaLat)!==0);
  await chooseMode('Set reach');
  await stage.locator('input[aria-label="Reach in kilometres"]').fill('3.25');
  await stage.getByRole('button',{name:'Apply reach'}).click();
  assert.equal(await areaForm.locator('[name="area_lat"]').inputValue(),areaLat,'Spatial subtools share the draft');
  await page.keyboard.press('Escape');
  assert.equal(await areaForm.locator('[name="area_lat"]').inputValue(),'','Escape discards unsaved direct-area position');
  await chooseMode('Edit route line');
  const priorLine=await areaForm.locator('[name="route_geojson"]').inputValue();
  await useMapPoint(-34.6,-70.5);
  await useMapPoint(-34.65,-70.55);
  await stage.getByRole('button',{name:'Finish line'}).click();
  const path=JSON.parse(await areaForm.locator('[name="route_geojson"]').inputValue());
  assert.equal(path.type,'LineString');assert.equal(path.coordinates.length,2);
  assert.ok(path.coordinates[0][0]<0&&path.coordinates[0][1]<0,'Signed southern/western route vertices preserved');
  await page.keyboard.press('Escape');
  assert.equal(await areaForm.locator('[name="route_geojson"]').inputValue(),priorLine);
  console.log('LIVE SPATIAL EDITING: enabled Draw/Edit, polygon draft/cancel, radius, direct area, route line, Escape PASS');
} finally {await browser.close();}
